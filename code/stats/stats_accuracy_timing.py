### Subfunctions

# From a given selection of columns, extract a stats-friendly dataframe.
# Semi-static, requires 'subject' and 'script', and will reshape the list of columns into 'day'
def reshape_table(tableIn, relevantCols):

    # melt table to sub-selection
    tableOut = pd.melt(tableIn, id_vars = ['subject', 'script'], 
                           value_vars = relevantCols,
                           var_name = 'day', 
                           value_name = 'target')

    # Extract day number from 'day' column
    tableOut['day'] = tableOut['day'].str.extract(r'(\d)').astype(int)

    # Sort the dataframe
    tableOut.sort_values(by=['subject', 'script', 'day'], inplace = True)


    return tableOut


# From a (supposedly correct) table
# - extract descriptive statistics for group * day
# - perform repeated measures / mixed ANOVA
def get_stats(tableIn):
    
    # Descriptive statistics
    desc = tableIn.groupby(['script', 'day']).agg(n = ('target', 'count'),
                                                  mean = ('target', 'mean'),
                                                  std = ('target', 'std')).reset_index()
    
    # rmANOVA
    anova = pg.mixed_anova(dv = 'target', 
                           within = 'day', 
                           between = 'script', 
                           subject = 'subject',
                           data = tableIn)
    
    # Return values
    return desc, anova


# Perform posthoc tests
def get_stats_posthoc(tableIn, opt):
    
    # Perform t-tests on the script diffrences across sessions
    # (four tests, on per session)
    ttests = []
    pvals = []
    for i in range(1,5):
        
        # Get the accuracy for given scripts on given sessions
        stat, pval = stats.ttest_ind(tableIn[(tableIn['script'] == 'br') & (tableIn['day'] == i)]['target'],
                                     tableIn[(tableIn['script'] == 'cb') & (tableIn['day'] == i)]['target'])
        
        # Add test information to the correct arrays
        ttests.append(stat)
        pvals.append(pval)
    
    
    # Correct for multiple comparisons
    bonf_pvals = multipletests(pvals, alpha = 0.05, method = 'bonferroni')
    fdr_pvals = fdrcorrection(pvals, alpha = 0.05)


    # Make stats over the group differences
    sessions = []
    ttests = []
    dofs = []
    pvals = []
    for i in range(1,5):
        
        session_col = f'session-{i}'
        
        # Select data for br and cb scripts for the current session column
        br_data = tableIn[(tableIn['script'] == 'br') & (tableIn['day'] == i)]['target']
        cb_data = tableIn[(tableIn['script'] == 'cb') & (tableIn['day'] == i)]['target']
        
        # Perform t-test between br and cb scripts for the given session
        stat, pval = stats.ttest_ind(br_data, cb_data)
        
        # Calculate degrees of freedom
        dof = len(br_data) + len(cb_data) - 2
            
        # Store the results
        sessions.append(session_col)
        ttests.append(stat)
        pvals.append(pval)
        dofs.append(dof)

    
    # Apply Bonferroni correction to the p-values
    _, bonf_pvals, _, _ = multipletests(pvals, alpha = 0.05, method = 'bonferroni')
    
    # Create a DataFrame with the results
    ttest_results = pd.DataFrame({
        'session': sessions,
        't_statistic': ttests,
        'deg_freedom': dofs,
        'p_value': pvals,
        'bonferroni_p_value': bonf_pvals
    })
    
    # Save the results
    ttest_results.to_csv(os.path.join(opt['dir']['results'], 'VBT_data-test_variable-accuracy_analysis-posthoc.csv'), index = False)

    
    return ttest_results


# Save results to csv
# - renames 'target' variable to either 'accuracy' or 'timing'
def save_stats(opt, tableIn, newVarName, filename):
    
    # rename variable from filename
    tableIn = tableIn.rename(columns = {'target': newVarName})
    
    # construct the filename
    filename = filename + '.csv'
    
    # save result
    tableIn.to_csv(os.path.join(opt['dir']['results'], filename), index = False)
    
    




    